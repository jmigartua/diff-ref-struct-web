// diff-ref-struct Web · the files the service worker keeps for offline use (I10 step 4): every file the page loads,
// found by walking it from index.html: its stylesheets, icons and manifest, its module script, and from each module
// its static imports and its import() of a literal path (the Surface's three.js), recursively. Written to
// app/ui/host-web/precache.json as paths relative to host-web/ ("../core.js"), each with its size; the wasm package is
// not listed (the worker takes it from wasm/manifest.json, which names it when built). A node test fails when the
// committed list is not what this gives.
//   node web/tools/precache.mjs            write the list
//   node web/tools/precache.mjs --check    exit 1 when the committed list is stale
import { readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** The references in a file's text, by its kind: an HTML page's href/src of local files, a module's imports. */
export function references(name, text) {
  const out = [];
  if (/\.html$/.test(name)) {
    for (const m of text.matchAll(/\b(?:href|src)="([^"#?]+)"/g)) out.push(m[1]);
  } else if (/\.m?js$/.test(name)) {
    for (const m of text.matchAll(/^\s*(?:import|export)\s+(?:[^"';]*?\sfrom\s+)?["']([^"']+)["']/gm)) out.push(m[1]);
    for (const m of text.matchAll(/\bimport\(\s*["']([^"']+)["']\s*\)/g)) out.push(m[1]);
  } else if (/\.webmanifest$/.test(name)) {
    try { for (const i of JSON.parse(text).icons || []) out.push(i.src); } catch (e) { /* not JSON */ }
  }
  return out.filter((r) => !/^(?:[a-z]+:|\/\/|data:)/i.test(r));
}

/** Every file reached from `entries` (paths relative to `base`), by `read(path) -> text | null`, in the order found;
    a reference to a missing file is returned in `missing`. Paths stay relative to `base`, POSIX-joined. */
export function closure(entries, read) {
  const seen = new Set(), order = [], missing = [];
  const walk = (p) => {
    if (seen.has(p)) return; seen.add(p);
    const text = read(p);
    if (text == null) { missing.push(p); return; }
    order.push(p);
    for (const r of references(p, text)) walk(path.posix.normalize(path.posix.join(path.posix.dirname(p), r)));
  };
  for (const e of entries) walk(e);
  return { files: order, missing };
}

const here = path.dirname(fileURLToPath(import.meta.url));
const ui = path.resolve(here, "../../app/ui");
/** The host's list, from the files on disk: walked from host-web/index.html (and the worker's own pieces). */
export function hostList() {
  const read = (p) => { const f = path.join(ui, p); return existsSync(f) && statSync(f).isFile() ? readFileSync(f, /\.(png|wasm|woff2?)$/.test(p) ? null : "utf8") : null; };
  const { files, missing } = closure(["host-web/index.html", "host-web/manifest.webmanifest", "host-web/version.json", "host-web/wasm/manifest.json"], read);
  return {
    files: files.map((f) => ({ path: path.posix.relative("host-web", f), bytes: statSync(path.join(ui, f)).size })),
    missing: missing.map((f) => path.posix.relative("host-web", f)),
  };
}
export const listText = (l) => JSON.stringify({ note: "Generated by web/tools/precache.mjs: the files the page loads, for the service worker (sw.js). Do not edit.", files: l.files.map((f) => f.path), bytes: l.files.reduce((n, f) => n + f.bytes, 0) }, null, 1) + "\n";

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const l = hostList();
  if (l.missing.length) { console.error(`precache: referenced and missing: ${l.missing.join(", ")}`); process.exit(1); }
  const out = path.join(ui, "host-web/precache.json"), text = listText(l);
  if (process.argv.includes("--check")) {
    const now = existsSync(out) ? readFileSync(out, "utf8") : "";
    // the sizes change with every edit; the list of files is what must be current
    const files = (t) => JSON.stringify((JSON.parse(t || "{}").files) || []);
    if (files(now) !== files(text)) { console.error("precache: host-web/precache.json is stale: node web/tools/precache.mjs"); process.exit(1); }
    console.log(`precache: ${l.files.length} files, current`);
  } else { writeFileSync(out, text); console.log(`precache: ${l.files.length} files, ${(l.files.reduce((n, f) => n + f.bytes, 0) / 1024).toFixed(0)} kB → app/ui/host-web/precache.json`); }
}
