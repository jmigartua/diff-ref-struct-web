#!/usr/bin/env python3
"""diff-ref-struct Web · the guide's generator (the open-tool kit's records rendered; run by Quarto before every render,
and by tools/pdf.sh for the PDFs' text).

  data/nav.yml           -> _gen/docs-nav.html      the left navigation and the reading column's opening (the kit's)
  ../manual/*.md         -> _gen/<name>.md          the manuals as the site shows them; the user manual with its three
                                                    appendices (A Conventions, B Release notes, C Roadmap)
  data/releases.yml      -> _gen/releases.md, _gen/known.html, feeds/releases.xml, ../CHANGELOG.md
  data/roadmap.yml       -> _gen/roadmap.md
  data/conventions.yml   -> _gen/conventions.md     (+ the project's file dictionary, ecosystem/data/files.yml)
  ecosystem/data/log.yml -> _gen/log.md, feeds/log.xml   the entries about this tool, none that names a team's data
  GitHub issues          -> _gen/requests.md        the public repository's requests, read at render time
  downloads/pdfs.json                               each PDF's source hash: a stale PDF is said (warning; --check fails)

One source per record, many renderings. The public guide never holds a team's unpublished data:
- a manual whose first lines say `<!-- edition: team -->` is a team's edition, refused by the public build (tools/pdf.sh
  builds it into web/manual/team/, never staged);
- `<!-- team-only -->` … `<!-- /team-only -->` parts are dropped from the public edition, `public-only` ones from a team's;
- a log entry holding one of the private words (web/private/guard.txt, outside the public source) is left out, counted.

  python3 tools/build.py                  the _gen files (Quarto's pre-render)
  python3 tools/build.py --check          also exit 1 when a PDF is stale
  python3 tools/build.py --source NAME --edition public|team    print a manual as the PDF takes it
  python3 tools/build.py --version        print the current release's version (stage.mjs, the release gate)
"""
import datetime
import hashlib
import html
import json
import re
import sys
import urllib.request
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SITE = HERE.parent
WEB = SITE.parent
TOP = WEB.parent
GEN = SITE / "_gen"
DATA = SITE / "data"
FEEDS = SITE / "feeds"
MANUALS = WEB / "manual"
DOWNLOADS = SITE / "downloads"
GUARD = WEB / "private" / "guard.txt"
PROJECT_LOG = TOP / "ecosystem" / "data" / "log.yml"
FILE_DICTIONARY = TOP / "ecosystem" / "data" / "files.yml"

SITE_URL = "https://jmigartua.github.io/diff-ref-struct-web/guide/"
REPO = "jmigartua/diff-ref-struct-web"
PUBLIC = ["user-manual", "quick-reference"]
WITH_APPENDICES = ["user-manual"]
# what makes a project log entry one about this tool
ABOUT_WEB = re.compile(r"\b(I10|R34)\b|web stream|web host|diff-ref-struct Web|host-web|publish-web|web/REQUESTS|\bweb/(site|manual|tools|tests)|web branch|browser host|the web app|drs-wasm", re.I)


def esc(s):
    return html.escape(str(s), quote=True)


def load(path, default=None):
    return yaml.safe_load(Path(path).read_text(encoding="utf-8")) if Path(path).exists() else default


def guard_words():
    if not GUARD.exists():
        return []
    return [w.strip() for w in GUARD.read_text(encoding="utf-8").splitlines() if w.strip() and not w.startswith("#")]


def guarded(text):
    low = text.lower()
    return [w for w in guard_words() if w.lower() in low]


# ------------------------------------------------------------------ navigation (the kit's markup)
def write_nav(groups):
    parts = ['<!-- generated by tools/build.py: left navigation + opening of the reading column -->',
             '<div class="docs">', '<nav class="docs-nav" aria-label="Site sections">',
             '<button class="docs-fold" type="button" data-fold="nav" aria-label="Hide the navigation" title="Hide the navigation">&lsaquo;</button>']

    def ul(items):
        return "<ul>" + "".join(f'<li><a href="{esc(i["href"])}">{esc(i["text"])}</a></li>' for i in items) + "</ul>"

    for g in groups:
        parts.append(f'<details class="group" open><summary class="t">{esc(g["title"])}</summary>{ul(g["items"])}</details>')
    parts += ["</nav>", '<div class="docs-main">', ""]
    (GEN / "docs-nav.html").write_text("\n".join(parts), encoding="utf-8")


# ------------------------------------------------------------------ the records, as Markdown
def releases():
    return load(DATA / "releases.yml", [])


def current():
    """The release the guide and the manuals describe: the newest entry (next or released)."""
    return releases()[0]


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |")
    return "\n".join(out) + "\n"


def conventions_md(level=2, intro=True):
    c = load(DATA / "conventions.yml", {})
    h = "#" * level
    out = [c.get("intro", "").strip() + "\n"] if intro else []
    out.append(f"{h} Words\n\n" + md_table(["word", "what it means"], [(f"**{w['term']}**", w["means"]) for w in c.get("words", [])]))
    rows = []
    d = load(FILE_DICTIONARY, {}) or {}
    kinds = {k["id"]: k for k in d.get("kinds", [])}
    for kid in c.get("dictionary", []):
        k = kinds.get(kid)
        if not k:
            continue
        where = f"`{k['folder']}/`" if k.get("folder") else "the project's folder"
        rows.append((f"`{k['pattern']}`", k["name"], k.get("contents") or "", where))
    for f in c.get("files", []):
        rows.append((f"`{f['suffix']}`", f["name"], f["means"], ""))
    note = "" if d else "\n*The project's file dictionary is not in this checkout: its kinds are left out of this table.*\n"
    out.append(f"{h} Files and suffixes\n\nThe project's own kinds come from its file dictionary (the same table that "
               f"names the files the core writes); the others are files the page meets.{note}\n\n"
               + md_table(["name or suffix", "kind", "what it holds", "where"], rows))
    n = c.get("naming", {})
    out.append(f"{h} Naming scans\n\n{n.get('intro', '').strip()}\n\n" + md_table(["in a name", "the core reads"], [(f"`{r['form']}`", r["means"]) for r in n.get("rows", [])]))
    out.append(f"{h} Units and signs\n\n" + md_table(["quantity", "unit"], [(u["quantity"], u["unit"]) for u in c.get("units", [])]))
    out.append(f"{h} Versions and ids\n\n" + md_table(["form", "what it is"], [(f"`{i['form']}`", i["means"]) for i in c.get("ids", [])]))
    return "\n".join(out)


def releases_md(level=2, upto=None):
    out = []
    h = "#" * level
    started = upto is None
    for r in releases():
        if not started:
            started = r["version"] == upto
            if not started:
                continue
        state = {"next": "to be published", "released": "published", "internal": "not published"}.get(r.get("status"), "")
        out.append(f"{h} {r['version']} · {r['title']}\n")
        out.append(f"*{r['date']} · {state} · core {r['core']} · build {r['build']}*\n")
        if r.get("summary"):
            out.append(r["summary"].strip() + "\n")
        for key, word in (("added", "Added"), ("changed", "Changed"), ("fixed", "Fixed"), ("known", "Known")):
            if r.get(key):
                out.append(f"**{word}**\n\n" + "\n".join(f"- {x}" for x in r[key]) + "\n")
        tail = []
        if r.get("closes"):
            tail.append("Closes " + ", ".join(r["closes"]))
        if r.get("log"):
            tail.append("log " + ", ".join(r["log"]))
        if r.get("evidence"):
            tail.append("evidence: " + r["evidence"])
        if tail:
            out.append("*" + "; ".join(tail) + ".*\n")
    return "\n".join(out)


def roadmap_md(level=2):
    words = {"decided": "Decided", "considered": "Considered", "set-aside": "Set aside"}
    out = []
    h = "#" * level
    for g in load(DATA / "roadmap.yml", []):
        out.append(f"{h} {words.get(g['status'], g['status'])}\n")
        for i in g["items"]:
            src = f" ({i['source']})" if i.get("source") else ""
            out.append(f"- **{i['title']}.** {i['why']}{src}")
        out.append("")
    return "\n".join(out)


# ------------------------------------------------------------------ the manuals
def edition_of(text):
    m = re.search(r"<!--\s*edition:\s*(\w+)", text[:600])
    return m.group(1) if m else "public"


def edition(text, which):
    drop = "team-only" if which == "public" else "public-only"
    keep = "public-only" if which == "public" else "team-only"
    text = re.sub(rf"<!-- {drop} -->.*?<!-- /{drop} -->\n?", "", text, flags=re.S)
    return re.sub(rf"<!-- /?{keep} -->\n?", "", text)


def body(name, which, target):
    """A manual as the site (`target` "site") or the PDF ("pdf") takes it: no H1, no hand-made contents, figure paths
    the page's, links between manuals resolved; the user manual with its appendices."""
    raw = (MANUALS / f"{name}.md").read_text(encoding="utf-8")
    if which == "public" and edition_of(raw) == "team":
        raise SystemExit(f"build: {name} is a team's edition (unpublished data): never in the public guide")
    text = edition(raw, which)
    text = re.sub(r"^<!--\s*edition:.*?-->\n", "", text, flags=re.S)
    lines = text.splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    text = "\n".join(lines).strip() + "\n"
    text = re.sub(r"\n---\n\n## Contents\n.*?\n---\n", "\n", text, flags=re.S)
    if name in WITH_APPENDICES:
        r = current()
        text += ("\n## Appendix A. Conventions\n\n" + conventions_md(3)
                 + f"\n## Appendix B. Release notes\n\nEvery version of diff-ref-struct Web up to {r['version']}, the one this "
                 "manual describes, newest first.\n\n" + releases_md(3, upto=r["version"])
                 + "\n## Appendix C. Roadmap\n\nWhat is decided, considered and set aside after this version.\n\n" + roadmap_md(3))
    if target == "pdf":
        text = text.replace("(user-manual.md)", f"({SITE_URL}manual/)").replace("(quick-reference.md)", f"({SITE_URL}manual/quick-reference/)")
        text = re.sub(r'<a id="[^"]+"></a>\n?', "", text)
    if target == "site":
        text = text.replace("](../site/assets/figures/", "](../assets/figures/")
        text = text.replace("(user-manual.md)", "(/manual/index.html)").replace("(quick-reference.md)", "(/manual/quick-reference/index.html)")
    return text


def digest(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def write_manuals():
    for name in PUBLIC:
        (GEN / f"{name}.md").write_text(body(name, "public", "site"), encoding="utf-8")
    m = re.search(r"\n## \d+\. The file formats the core reads\n(.*?)\n## ", body("user-manual", "public", "site"), flags=re.S)
    if not m:
        raise SystemExit("build: the manual has no section 'The file formats the core reads'")
    (GEN / "formats.md").write_text(m.group(1).strip() + "\n", encoding="utf-8")


def check_pdfs(strict):
    rec = json.loads((DOWNLOADS / "pdfs.json").read_text(encoding="utf-8")) if (DOWNLOADS / "pdfs.json").exists() else {}
    ok = True
    for name in PUBLIC:
        pdf = DOWNLOADS / f"{name}.pdf"
        now = digest(body(name, "public", "pdf"))
        if not pdf.exists():
            say = f"build: downloads/{name}.pdf is missing: run web/site/tools/pdf.sh"
        elif rec.get(name, {}).get("sha256") != now:
            say = f"build: downloads/{name}.pdf is older than its sources (the manual or the records): run web/site/tools/pdf.sh"
        else:
            continue
        ok = False
        print(("" if strict else "::warning::") + say, file=sys.stderr)
    return ok


# ------------------------------------------------------------------ pages from the records
def write_records():
    (GEN / "conventions.md").write_text(conventions_md(2, intro=False), encoding="utf-8")
    (GEN / "releases.md").write_text(releases_md(2), encoding="utf-8")
    (GEN / "roadmap.md").write_text(roadmap_md(2), encoding="utf-8")
    r = current()
    known = "".join(f"<li>{esc(k)}</li>" for k in r.get("known", []))
    (GEN / "known.html").write_text(
        f'<div class="known"><div class="k">Known in {esc(r["version"])}</div><ul>{known}</ul>'
        f'<a href="/releases/index.html">Release notes &rarr;</a></div>\n' if known else "", encoding="utf-8")
    # the CHANGELOG of the source, generated (never edited by hand)
    (WEB / "CHANGELOG.md").write_text("# Changelog of diff-ref-struct Web\n\n*Generated from web/site/data/releases.yml by "
                                      "web/site/tools/build.py; edit the record, not this file.*\n\n" + releases_md(2), encoding="utf-8")


def log_entries():
    entries = load(PROJECT_LOG, None)
    if entries is None:
        return None, 0
    out, hidden = [], 0
    for e in entries:
        text = " ".join(str(e.get(k, "")) for k in ("title", "body", "source"))
        if not ABOUT_WEB.search(text):
            continue
        if guarded(text):
            hidden += 1
            continue
        out.append(e)
    return list(reversed(out)), hidden


def write_log():
    entries, hidden = log_entries()
    if entries is None:
        (GEN / "log.md").write_text("*The project's log is not in this checkout: the log is rendered from it at publication.*\n", encoding="utf-8")
        return []
    words = {"finding": "finding", "decision": "decision", "work": "work"}
    out = [f"{len(entries)} entries about this tool, newest first, from the project's log"
           + (f"; {hidden} more concern a team's unpublished data and are not shown here" if hidden else "") + ".\n"]
    for e in entries:
        out.append(f"### {e['id']} · {e['title']}\n")
        out.append(f"*{e['date']} · {words.get(e.get('kind'), e.get('kind', ''))}*\n")
        out.append(str(e.get("body", "")).strip() + "\n")
        if e.get("source"):
            out.append(f"<p class=\"cite\">{esc(e['source'])}</p>\n")
    (GEN / "log.md").write_text("\n".join(out), encoding="utf-8")
    return entries


def write_requests():
    """The public repository's issues, read at render time (no token: 60 requests an hour suffice for a render)."""
    head = ("How to ask: the [bug form](https://github.com/" + REPO + "/issues/new?template=bug.yml) or the "
            "[feature form](https://github.com/" + REPO + "/issues/new?template=feature.yml), or from the page's "
            "**Help ▾** menu, which fills in the version, the browser and the view's address for you. Without a GitHub "
            "account, write to josu.igartua@ehu.eus with the same three things. Never attach unpublished data: a "
            "description and the view's address are enough.\n\n")
    try:
        req = urllib.request.Request(f"https://api.github.com/repos/{REPO}/issues?state=all&per_page=100",
                                     headers={"Accept": "application/vnd.github+json", "User-Agent": "diff-ref-struct-web-guide"})
        issues = [i for i in json.load(urllib.request.urlopen(req, timeout=10)) if "pull_request" not in i]
    except Exception as e:  # offline, rate-limited, or no issues yet
        (GEN / "requests.md").write_text(head + f"*The list of requests could not be read at this render ({type(e).__name__}); "
                                         f"[the issues on GitHub](https://github.com/{REPO}/issues) are the list.*\n", encoding="utf-8")
        return
    def row(i):
        labels = ", ".join(l["name"] for l in i.get("labels", []))
        return (f"[#{i['number']}]({i['html_url']})", esc(i["title"]), labels, i["created_at"][:10], i.get("closed_at", "") and i["closed_at"][:10] or "")
    open_ = [row(i) for i in issues if i["state"] == "open"]
    closed = [row(i) for i in issues if i["state"] == "closed"]
    out = [head, f"*Read from the public repository at this render: {len(open_)} open, {len(closed)} closed.*\n"]
    out.append("## Open\n\n" + (md_table(["#", "request", "labels", "opened"], [r[:4] for r in open_]) if open_ else "None open.\n"))
    out.append("## Done\n\n" + (md_table(["#", "request", "labels", "opened", "closed"], closed) if closed else "None closed yet.\n"))
    (GEN / "requests.md").write_text("\n".join(out), encoding="utf-8")


# ------------------------------------------------------------------ feeds (Atom)
def atom(name, title, items):
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    entries = "".join(
        f"<entry><id>{esc(SITE_URL + i['path'])}#{esc(i['id'])}</id><title>{esc(i['title'])}</title>"
        f"<updated>{esc(i['date'])}T00:00:00Z</updated><link href=\"{esc(SITE_URL + i['path'])}\"/>"
        f"<summary>{esc(i['summary'])}</summary></entry>" for i in items)
    FEEDS.mkdir(exist_ok=True)
    (FEEDS / f"{name}.xml").write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<feed xmlns="http://www.w3.org/2005/Atom"><title>{esc(title)}</title>'
        f'<id>{esc(SITE_URL)}feeds/{name}.xml</id><updated>{now}</updated><author><name>Josu M. Igartua</name></author>'
        f'<link href="{esc(SITE_URL)}"/>{entries}</feed>\n', encoding="utf-8")


def write_feeds(log):
    atom("releases", "diff-ref-struct Web · releases",
         [{"id": r["version"], "title": f"{r['version']} · {r['title']}", "date": r["date"], "path": "releases/",
           "summary": r.get("summary", "")} for r in releases() if r.get("status") != "internal"])
    atom("log", "diff-ref-struct Web · log",
         [{"id": e["id"], "title": f"{e['id']} · {e['title']}", "date": str(e["date"]), "path": "log/",
           "summary": str(e.get("body", ""))[:400]} for e in (log or [])[:40]])


def main():
    args = sys.argv[1:]
    if "--version" in args:
        print(current()["version"])
        return
    if "--source" in args:
        name = args[args.index("--source") + 1]
        which = args[args.index("--edition") + 1] if "--edition" in args else "public"
        sys.stdout.write(body(name, which, "pdf"))
        return
    GEN.mkdir(exist_ok=True)
    write_nav(load(DATA / "nav.yml"))
    write_records()
    write_manuals()
    log = write_log()
    write_requests()
    write_feeds(log)
    ok = check_pdfs("--check" in args)
    if "--check" in args and not ok:
        sys.exit(1)


if __name__ == "__main__":
    main()
