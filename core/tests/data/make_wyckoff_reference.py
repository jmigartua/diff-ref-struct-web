#!/usr/bin/env python3
"""Write wyckoff_230.txt, the reference for the test `spglib_wyckoff` (core/tests/spglib_wyckoff.rs).

spglib (https://spglib.readthedocs.io, BSD-3) is used only here, in the test-data step: `pip install spglib`, then
    python3 make_wyckoff_reference.py <path to spglib's database/Wyckoff.csv> > wyckoff_230.txt

For every Wyckoff position of the standard setting of each of the 230 types (spglib's first Hall number of the type),
a structure is built: species 1 on the position (its coordinate triplet from Wyckoff.csv, with x = 0.1123, y = 0.2357,
z = 0.3571, and a second time with x = 0.3089, y = 0.4153, z = 0.1847), its orbit generated by spglib's stored
operators, and species 2 on a general position (0.0613, 0.1871, 0.2919) so that the structure has exactly the
symmetry of the group. spglib's `get_symmetry_dataset` then finds the group and the Wyckoff letter and site-symmetry
symbol of the species-1 atoms; the multiplicity is their number in the conventional cell. Only structures that spglib
leaves in the same setting (same Hall number, identity transformation, no origin shift) are written, so that the
letters refer to the coordinates as given. One line per structure:

    <hall_number> <number> <letter> <multiplicity> <site symmetry> <x> <y> <z>
"""
import re, sys
import numpy as np
import spglib

GENERAL = np.array([0.0613, 0.1871, 0.2919])
PARAMS = [dict(x=0.1123, y=0.2357, z=0.3571), dict(x=0.3089, y=0.4153, z=0.1847)]


def table(path):
    t, h = {}, None
    for line in open(path):
        line = line.rstrip("\n")
        m = re.match(r"^(\d+):", line)
        if m:
            h = int(m.group(1)); t[h] = []; continue
        f = line.split(":")
        if len(f) > 5 and f[2]:
            t[h].append(dict(mult=int(f[2]), letter=f[3], site=f[4], coord=f[5]))
    return t


def lattice(h):
    """A cell of the right metric for the setting; triclinic cells are Niggli-reduced (all angles obtuse)."""
    t = spglib.get_spacegroup_type(h); n, ch = t.number, t.choice
    a, b, c, al, be, ga = 9.1, 10.7, 12.3, 90, 90, 90
    if n <= 2:
        al, be, ga = 95, 100, 105
    elif n <= 15:
        al, be, ga = {"b": (90, 101, 90), "c": (90, 90, 101), "a": (101, 90, 90)}[(ch or "b")[0]]
    elif n <= 74:
        pass
    elif n <= 142:
        b = a
    elif n <= 194:
        if ch == "R":
            b = c = a; al = be = ga = 72
        else:
            b = a; ga = 120
    else:
        b = c = a
    al, be, ga = np.radians([al, be, ga])
    v = np.sqrt(1 - np.cos(al)**2 - np.cos(be)**2 - np.cos(ga)**2 + 2*np.cos(al)*np.cos(be)*np.cos(ga))
    return np.array([[a, 0, 0], [b*np.cos(ga), b*np.sin(ga), 0],
                     [c*np.cos(be), c*(np.cos(al) - np.cos(be)*np.cos(ga))/np.sin(ga), c*v/np.sin(ga)]])


def orbit(h, p):
    s = spglib.get_symmetry_from_database(h); pts = []
    for r, t in zip(s["rotations"], s["translations"]):
        q = (r @ p + t) % 1.0
        if not any(np.allclose(((q - x + 0.5) % 1) - 0.5, 0, atol=1e-7) for x in pts):
            pts.append(q)
    return pts


def point(coord, vals):
    return np.array([eval(re.sub(r"(\d)([xyz])", r"\1*\2", e), {}, vals) for e in coord.strip("()").split(",")]) % 1.0


def main():
    T = table(sys.argv[1])
    std = {}
    for h in range(1, 531):
        std.setdefault(spglib.get_spacegroup_type(h).number, h)
    print(f"# spglib {spglib.__version__} get_symmetry_dataset on structures built from Wyckoff.csv; standard settings")
    print("# hall_number number letter multiplicity site_symmetry x y z; written by make_wyckoff_reference.py")
    skipped = 0
    for n, h in sorted(std.items()):
        L = lattice(h); gen = orbit(h, GENERAL)
        for w in T[h]:
            for vals in PARAMS:
                p = point(w["coord"], vals); sp = orbit(h, p)
                d = spglib.get_symmetry_dataset((L, np.array(sp + gen), [1]*len(sp) + [2]*len(gen)), symprec=1e-5)
                same = (d.number == n and d.hall_number == h and np.allclose(d.transformation_matrix, np.eye(3))
                        and np.allclose(((d.origin_shift + 0.5) % 1) - 0.5, 0, atol=1e-7))
                if not same:
                    skipped += 1; continue
                letters, sites = set(d.wyckoffs[:len(sp)]), set(d.site_symmetry_symbols[:len(sp)])
                assert len(letters) == 1 and len(sites) == 1, (h, w)
                print(h, n, letters.pop(), len(sp), sites.pop(), " ".join(f"{x:.10f}" for x in p))
    print(f"# structures not left in their setting by spglib, not written: {skipped}")


main()
