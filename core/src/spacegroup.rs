/// A group is written as its Hall symbol and its operators, and read back from the symbol (or, when the symbol does
/// not give the same operators, from the operators): the model as text (the app's request 1, L058).
#[cfg(feature = "serde")]
mod serde_impl {
    use super::SpaceGroup;
    use crate::symop::SymOp;

    #[derive(serde::Serialize, serde::Deserialize)]
    struct Written {
        hall: String,
        ops: Vec<String>,
    }

    impl serde::Serialize for SpaceGroup {
        fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
            Written { hall: self.hall.clone(), ops: self.ops.iter().map(|o| o.to_xyz()).collect() }.serialize(s)
        }
    }

    impl<'de> serde::Deserialize<'de> for SpaceGroup {
        fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<SpaceGroup, D::Error> {
            let w = Written::deserialize(d)?;
            let ops = w.ops.iter().map(|t| SymOp::parse_xyz(t)).collect::<Result<Vec<_>, _>>().map_err(serde::de::Error::custom)?;
            match SpaceGroup::from_hall(&w.hall) {
                Ok(g) if g.ops == ops => Ok(g),
                _ => SpaceGroup::from_operators(&ops).map_err(serde::de::Error::custom),
            }
        }
    }
}
